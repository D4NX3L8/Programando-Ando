package guia1.ciclos;

/**
 * Guia 1 - Ejercicio 11 (Basico)
 * Numeros del 1 al 50
 *
 * Enunciado:
 * Imprime los numeros del 1 al 50 usando un ciclo for.
 *
 * Autor: Jeronimo Henao
 */

public class Ej11 {

    public static void main(String[] args) {

        for (int i = 1; i <= 50; i++) {
            System.out.println(i);
        }

    }
}
